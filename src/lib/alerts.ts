import "server-only"
import { logger } from "@/lib/logger"

export interface AlertPayload {
  severity: "P0" | "P1" | "P2" | "P3"
  title: string
  service: string
  summary: string
  firstSeen: string
  latestSeen: string
  count: number
  fingerprint: string
  remediationHint?: string
}

export async function sendAlert(payload: AlertPayload): Promise<void> {
  await Promise.allSettled([sendEmailAlert(payload), createGitHubIssue(payload)])
}

async function sendEmailAlert(payload: AlertPayload): Promise<void> {
  const apiKey = process.env.RESEND_API_KEY
  const to = process.env.ALERT_EMAIL ?? process.env.VAPID_EMAIL?.replace("mailto:", "")
  if (!apiKey || !to) return

  const severityEmoji = { P0: "🔴", P1: "🟠", P2: "🟡", P3: "🔵" }[payload.severity]
  const subject = `${severityEmoji} [${payload.severity}] ${payload.service}: ${payload.title}`
  const html = `
<h2>${severityEmoji} ${payload.severity} — ${payload.title}</h2>
<table>
  <tr><td><strong>Service</strong></td><td>${payload.service}</td></tr>
  <tr><td><strong>Summary</strong></td><td>${escapeHtml(payload.summary)}</td></tr>
  <tr><td><strong>First seen</strong></td><td>${payload.firstSeen}</td></tr>
  <tr><td><strong>Latest</strong></td><td>${payload.latestSeen}</td></tr>
  <tr><td><strong>Occurrences</strong></td><td>${payload.count}</td></tr>
  ${payload.remediationHint ? `<tr><td><strong>Hint</strong></td><td>${escapeHtml(payload.remediationHint)}</td></tr>` : ""}
</table>
<p style="color:#888;font-size:12px">KidsXtra SRE · fingerprint: ${payload.fingerprint}</p>
  `.trim()

  try {
    const res = await fetch("https://api.resend.com/emails", {
      method: "POST",
      headers: { Authorization: `Bearer ${apiKey}`, "Content-Type": "application/json" },
      body: JSON.stringify({ from: "alerts@kidsxtra.cc", to, subject, html }),
    })
    if (!res.ok) {
      logger.warn("alert_email_failed", { status: res.status, fingerprint: payload.fingerprint })
    }
  } catch (err) {
    logger.error("alert_email_error", { error: err instanceof Error ? err.message : String(err) })
  }
}

async function createGitHubIssue(payload: AlertPayload): Promise<void> {
  const token = process.env.GITHUB_TOKEN
  const repo = process.env.GITHUB_ALERT_REPO
  if (!token || !repo) return

  const labels = ["incident", payload.severity.toLowerCase()]
  const body = [
    `## ${payload.title}`,
    ``,
    `**Severity:** ${payload.severity}  `,
    `**Service:** ${payload.service}  `,
    `**First seen:** ${payload.firstSeen}  `,
    `**Latest:** ${payload.latestSeen}  `,
    `**Occurrences:** ${payload.count}  `,
    `**Fingerprint:** \`${payload.fingerprint}\``,
    ``,
    `### Summary`,
    payload.summary,
    payload.remediationHint ? `\n### Suggested remediation\n${payload.remediationHint}` : "",
    ``,
    `---`,
    `*Auto-generated by KidsXtra SRE alerting. Never contains child PII.*`,
  ]
    .filter((l) => l !== undefined)
    .join("\n")

  try {
    const res = await fetch(`https://api.github.com/repos/${repo}/issues`, {
      method: "POST",
      headers: {
        Authorization: `Bearer ${token}`,
        Accept: "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
        "Content-Type": "application/json",
      },
      body: JSON.stringify({ title: `[${payload.severity}] ${payload.title}`, body, labels }),
    })
    if (!res.ok) {
      logger.warn("github_issue_failed", { status: res.status, fingerprint: payload.fingerprint })
    }
  } catch (err) {
    logger.error("github_issue_error", { error: err instanceof Error ? err.message : String(err) })
  }
}

function escapeHtml(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
}
